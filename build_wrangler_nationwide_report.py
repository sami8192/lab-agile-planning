def section_results(fw):
    s = [CondPageBreak(3.0 * inch),
         P('5.  Filter results - all %d vehicles' % len(RESULTS), 'h1'), rule()]
    s.append(P('Generated directly by wrangler_filter.py. VIN, year, generation and body come '
               'from the VIN; price, mileage and location are REPORTED.', 'small'))
    rows = []
    for r in RESULTS:
        loc = ', '.join(x for x in (r.get('city'), r.get('state')) if x) or 'n/a'
        price = money(r['price']) if r.get('price') else 'price n/a'
        miles = format(r['miles'], ',') + ' mi' if r.get('miles') else 'miles n/a'
        reported = '%s<br/>%s | %s<br/>%s' % (r.get('trim', ''), price, miles, loc)
        why = ['<font color="%s">x</font> %s' % (hx(RUST), h) for h in r['hard']]
        why += ['<font color="%s">!</font> %s' % (hx(AMBER), f) for f in r['flags']]
        rows.append([tag(r['decision'], DECISION_COL[r['decision']]),
                     Paragraph(r['vin'], S['mono']),
                     Paragraph('<b>%s</b> %s<br/>%s' % (r['year'], r['gen'] or '',
                                                       r['body']), S['cell']),
                     Paragraph(reported, S['cell']),
                     Paragraph('<br/>'.join(why) or 'Clean', S['cell'])])
    s.append(datatable(['Decision', 'VIN', 'From VIN', 'Reported listing', 'Reasons and flags'],
                       rows, [1.04 * inch, 1.42 * inch, 0.68 * inch, 1.42 * inch,
                              fw - 4.56 * inch]))
    return s


