AMBER_BG = colors.HexColor('#f7f1de')
DECISION_COL = {wf.SHORTLIST: GREEN, wf.CONDITIONAL_D: OLIVE, wf.REVIEW: AMBER,
                wf.EXCLUDED: RUST}

RESULTS = wf.run(wf.CANDIDATES)
COUNT = {k: sum(1 for r in RESULTS if r['decision'] == k)
         for k in (wf.SHORTLIST, wf.CONDITIONAL_D, wf.REVIEW, wf.EXCLUDED)}


def money(v):
    return '$' + format(v, ',') if v else 'n/a'


def story(fw):
    s = [NextPageTemplate('body')]
    s += cover(fw)
    s.append(PageBreak())
    for fn in (section_answer, section_caveats, section_rules, section_budget,
               section_results, section_shortlist, section_leads, section_inspection,
               section_tool, section_plan, section_sources):
        s += fn(fw)
    return s


