def section_rules(fw):
    s = [CondPageBreak(3.0 * inch), P('3.  The filter rules', 'h1'), rule()]
    s.append(P('3.1  Model years', 'h2'))
    yrows = []
    for y in range(1997, 2019):
        if y in wf.APPROVED:
            g, tier, why = wf.APPROVED[y]
            yrows.append([str(y), g, tag('TIER ' + tier, GREEN if tier == 'A' else OLIVE), why])
        elif y in wf.CONDITIONAL:
            g, why = wf.CONDITIONAL[y]
            yrows.append([str(y), g, tag('CONDITIONAL', OLIVE), why])
        else:
            yrows.append([str(y), 'TJ' if y < 2007 else 'JK', tag('EXCLUDED', RUST),
                          wf.EXCLUDED_YEARS[y]])
    # Collapse consecutive years that share a verdict and reason.
    merged = []
    for r in yrows:
        key = (r[1], r[2].text, r[3])
        if merged and merged[-1][0] == key:
            merged[-1][1].append(r[0])
        else:
            merged.append([key, [r[0]], r])
    data = []
    for key, years, r in merged:
        span = years[0] if len(years) == 1 else '%s-%s' % (years[0], years[-1])
        data.append([Paragraph('<b>%s</b>' % span, S['cell']), Paragraph(r[1], S['cell']),
                     r[2], Paragraph(r[3], S['cell'])])
    data.append([Paragraph('<b>2019+</b>', S['cell']), Paragraph('JL', S['cell']),
                 tag('EXCLUDED', RUST), Paragraph('JL generation - outside this search and '
                                                  'above budget', S['cell'])])
    s.append(datatable(['Years', 'Gen', 'Verdict', 'Reason'], data,
                       [0.8 * inch, 0.45 * inch, 1.05 * inch, fw - 2.3 * inch]))
    s.append(Spacer(1, 6))
    s.append(P('3.2  Other automatic exclusions', 'h2'))
    s.append(bullets([
        '<b>Engine</b> - TJs must carry the 4.0 inline six (VIN position 8 = S); JKs the 3.6 '
        'Pentastar (position 8 = G). This removes four-cylinder TJs and 3.8L JKs even when the '
        'advert says otherwise.',
        '<b>Check digit</b> - a VIN that fails is not a genuine VIN.',
        '<b>Title and channel</b> - salvage, rebuilt or flood titles; insurance-auction '
        'total losses; historical sales that are no longer for sale.',
        '<b>Country</b> - non-US listings (a Quebec car surfaced; importing adds cost and '
        'Quebec is heavy-salt).',
        '<b>Price</b> over $12,000.',
        '<b>TJ frames from heavy-salt states</b> - a TJ frame rots from the inside out and '
        'cannot be economically repaired, so a TJ from the Northeast or Midwest is excluded '
        'outright. This is a policy choice; it is one line in the code if you want them '
        'reviewed instead.',
    ]))
    s.append(KeepTogether([P('3.3  Flags - kept, but a person must resolve them', 'h2'), P(
        'Listing year contradicted by the VIN; price or mileage missing; priced over 15% below '
        'book; over 150,000 miles; flood region (Florida, Louisiana, Mississippi, Gulf-coast '
        'Texas); road-salt states; online auctions; modified vehicles; Unlimited body in a '
        'year whose book value starts above budget. Serious flags (below book, flood region, '
        'auction, modified, likely over budget) move a car from SHORTLIST to REVIEW.',
        'body')]))
    s.append(P(
        'Shortlisted cars are ranked by tier, then data completeness, mileage and climate, '
        'with a bonus for the JK - your stated preference, and the only generation with '
        'stability control.', 'small'))
    return s


